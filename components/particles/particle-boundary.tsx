"use client";

import { Component, type ReactNode } from "react";

/** Dynamic chunk/render failures leave the decorative CSS fallback intact. */
export class ParticleBoundary extends Component<
  { children: ReactNode; onError: () => void },
  { failed: boolean }
> {
  state = { failed: false };

  static getDerivedStateFromError() {
    return { failed: true };
  }

  componentDidCatch() {
    this.props.onError();
  }

  render() {
    return this.state.failed ? null : this.props.children;
  }
}
